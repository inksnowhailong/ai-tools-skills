#!/usr/bin/env node
/**
 * tvs-boss 面板「一键启动器」生成器 —— 按团队生成，落到团队根的 .tvs-boss/ 里。
 *
 * 为什么要"生成"而不是把启动器塞进 skill 源码：
 *   - 启动器是「运行态产物」，每个用户的团队根各异，属于团队数据（.tvs-boss/）而非工具本体。
 *   - 启动器是「薄壳」：运行时同时自定位两样——团队根（%~dp0 / $(dirname)）+ 本机 skill 里的
 *     open-panel.mjs（探 ~/.claude → ~/.cursor → CC 插件缓存 plugins/cache/tvs-inksnow/...）。
 *     两者都不写死绝对路径，平台开窗逻辑全在 open-panel 一处。
 *
 * 用法：node make-launcher.mjs --root <团队根>
 *   把 panel.cmd（Windows）和 panel.command（mac/linux）都写进 <团队根>/.tvs-boss/。
 *   两个平台的都生成，且零绝对路径——同步过去的团队目录换台机器（只要本机装了 tvs-boss）也开箱即用。
 *
 * /tvs-boss 启动协议在「建团 / 恢复团队」时调用本脚本，即可让每个用户初始化后就地有启动器。
 */
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

// open-panel.mjs 在 skill 内的相对位置（同目录）。启动器在【运行时】于本机 skill 安装目录下定位它，
// 而非把生成机的绝对路径烘焙进去——否则团队目录同步给别人时会指向不存在的路径（同事报的"缺少 js 文件"）。
const REL = 'skills/tvs-boss/scripts/open-panel.mjs';
const REL_WIN = REL.replace(/\//g, '\\');

/**
 * Windows 启动器（.cmd）：薄壳——运行时自定位团队根（%~dp0）+ 本机 skill 里的 open-panel.mjs。
 * 探测顺序 ~/.claude → ~/.cursor，两处都没有则提示先在本机装 tvs-boss。
 * 开窗/wt 检测等逻辑全收敛在 open-panel.mjs 一处（单一真源，改窗口行为不用动两份）。
 */
function cmdTemplate() {
    // 注意：.cmd 正文保持纯 ASCII —— cmd.exe 在 chcp 生效前用 OEM 代码页(GBK)解析批处理字节，
    // 中文注释/echo 会被当成命令报错。中文交给被拉起的 node TUI 去显示。
    return [
        '@echo off',
        'rem tvs-boss panel launcher (generated by make-launcher.mjs; do NOT commit to skill source)',
        'rem Thin shim: self-locate team root via %~dp0 AND open-panel.mjs via local skill install.',
        'rem No absolute paths are baked in, so a synced team dir works on any machine.',
        'set "HERE=%~dp0"',
        'set "HERE=%HERE:~0,-1%"',
        `set "OP=%USERPROFILE%\\.claude\\${REL_WIN}"`,
        `if not exist "%OP%" set "OP=%USERPROFILE%\\.cursor\\${REL_WIN}"`,
        'rem CC plugin install: skill lives under plugins\\cache\\<marketplace>\\<plugin>\\<version>\\ (last match wins)',
        `if not exist "%OP%" for /d %%D in ("%USERPROFILE%\\.claude\\plugins\\cache\\tvs-inksnow\\tvs-inksnow\\*") do if exist "%%D\\${REL_WIN}" set "OP=%%D\\${REL_WIN}"`,
        'if not exist "%OP%" (',
        '  echo [tvs-boss] open-panel.mjs not found under %USERPROFILE%\\.claude or \\.cursor.',
        '  echo Install the tvs-boss skill on this machine first ^(see ai-tools-skills README^).',
        '  pause',
        '  exit /b 1',
        ')',
        'node "%OP%" --root "%HERE%"',
        '',
    ].join('\r\n');
}

/**
 * macOS/Linux 启动器（.command）：薄壳——运行时自定位团队根 + 本机 skill 里的 open-panel.mjs。
 * 探测顺序 ~/.claude → ~/.cursor，开窗逻辑在 open-panel.mjs 一处。
 */
function shTemplate() {
    return [
        '#!/usr/bin/env bash',
        '# tvs-boss panel launcher (generated by make-launcher.mjs; do NOT commit to skill source)',
        '# Thin shim: self-locate team root AND open-panel.mjs via local skill install (no baked paths).',
        'HERE="$(cd "$(dirname "$0")" && pwd)"',
        `OP="$HOME/.claude/${REL}"`,
        `[ -f "$OP" ] || OP="$HOME/.cursor/${REL}"`,
        '# CC plugin install: skill lives under plugins/cache/<marketplace>/<plugin>/<version>/ (last match wins)',
        `if [ ! -f "$OP" ]; then for d in "$HOME"/.claude/plugins/cache/tvs-inksnow/tvs-inksnow/*/; do [ -f "\${d}${REL}" ] && OP="\${d}${REL}"; done; fi`,
        '[ -f "$OP" ] || { echo "[tvs-boss] open-panel.mjs not found under ~/.claude, ~/.cursor, or the tvs-inksnow plugin cache; install the tvs-boss skill on this machine first."; exit 1; }',
        'node "$OP" --root "$HERE"',
        '',
    ].join('\n');
}

function main() {
    const rootArg = process.argv.indexOf('--root');
    if (rootArg < 0 || !process.argv[rootArg + 1]) {
        console.error('用法：node make-launcher.mjs --root <团队根>');
        process.exit(1);
    }
    const teamRoot = resolve(process.argv[rootArg + 1]);
    const dotDir = join(teamRoot, '.tvs-boss');
    if (!existsSync(dotDir)) mkdirSync(dotDir, { recursive: true });

    const cmdPath = join(dotDir, 'panel.cmd');
    const shPath = join(dotDir, 'panel.command');
    writeFileSync(cmdPath, cmdTemplate());
    writeFileSync(shPath, shTemplate(), { mode: 0o755 }); // mac/linux 需可执行位

    console.log('已生成启动器（运行时在本机 ~/.claude、~/.cursor 或 CC 插件缓存下定位 open-panel.mjs，零绝对路径）：');
    console.log('  ' + cmdPath);
    console.log('  ' + shPath);
}

main();
