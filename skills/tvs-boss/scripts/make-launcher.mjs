#!/usr/bin/env node
/**
 * tvs-boss 面板「一键启动器」生成器 —— 按团队生成，落到团队根的 .tvs-boss/ 里。
 *
 * 为什么要"生成"而不是把启动器塞进 skill 源码：
 *   - 启动器是「运行态产物」，每个用户的团队根各异，属于团队数据（.tvs-boss/）而非工具本体。
 *   - 启动器里唯一的机器相关值是 panel.mjs 的安装路径——它在【生成这一刻】由本脚本自身位置算出，
 *     绝不写回 skill 源码；团队根则由启动器运行时用 %~dp0 / $(dirname) 自定位，零硬编码盘符。
 *
 * 用法：node make-launcher.mjs --root <团队根>
 *   把 panel.cmd（Windows）和 panel.command（mac/linux）都写进 <团队根>/.tvs-boss/。
 *   两个平台的都生成——同步过去的团队目录换台机器也开箱即用。
 *
 * /tvs-boss 启动协议在「建团 / 恢复团队」时调用本脚本，即可让每个用户初始化后就地有启动器。
 */
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// panel.mjs 绝对路径：由本生成器自身位置推出（与 panel.mjs 同目录），生成器内也零硬编码
const PANEL = join(dirname(fileURLToPath(import.meta.url)), 'panel.mjs');

/**
 * Windows 启动器（.cmd）：弹一个正经 PowerShell 窗口跑 TUI（支持 ANSI，避开老 conhost 渲染花）；
 * 检测到 Windows Terminal 则优先用 wt 开新 tab。团队根用 %~dp0 自定位（启动器就躺在 .tvs-boss/ 里）。
 * @param {string} panelPath 生成时填入的 panel.mjs 绝对路径
 */
function cmdTemplate(panelPath) {
    // 注意：.cmd 正文保持纯 ASCII —— cmd.exe 在 chcp 生效前用 OEM 代码页(GBK)解析批处理字节，
    // 中文注释/echo 会被当成命令报错。中文交给被拉起的 node TUI 去显示。
    return [
        '@echo off',
        'rem tvs-boss panel launcher (generated by make-launcher.mjs; do NOT commit to skill source)',
        'rem Self-locating: %~dp0 is this .tvs-boss dir; pass it as --root (panel.mjs resolves the team root).',
        'rem panel.mjs path below is filled at generation time from the skill install location.',
        '',
        'rem strip trailing backslash off %~dp0 so it interpolates cleanly inside the PowerShell -Command string',
        'set "HERE=%~dp0"',
        'set "HERE=%HERE:~0,-1%"',
        `set "PANEL=${panelPath}"`,
        '',
        'rem Prefer Windows Terminal (best ANSI); fall back to a normal PowerShell window. Detection is at RUNTIME.',
        'where wt >nul 2>nul',
        'if %errorlevel%==0 (',
        `  start "" wt new-tab powershell -NoExit -Command "node '%PANEL%' --root '%HERE%'"`,
        ') else (',
        `  start "" powershell -NoExit -Command "node '%PANEL%' --root '%HERE%'"`,
        ')',
        '',
    ].join('\r\n');
}

/**
 * macOS/Linux 启动器（.command，双击即在 Terminal.app 开窗）：用 osascript 弹 Terminal 跑 TUI。
 * 团队根用 $(dirname "$0") 自定位。
 * @param {string} panelPath 生成时填入的 panel.mjs 绝对路径
 */
function shTemplate(panelPath) {
    return [
        '#!/usr/bin/env bash',
        '# tvs-boss panel launcher (generated by make-launcher.mjs; do NOT commit to skill source)',
        '# Self-locating: HERE is this .tvs-boss dir; pass it as --root (panel.mjs resolves the team root).',
        '# panel.mjs path below is filled at generation time from the skill install location.',
        'HERE="$(cd "$(dirname "$0")" && pwd)"',
        `PANEL="${panelPath}"`,
        '# macOS: pop a Terminal window (supports ANSI). On Linux fall back to running in current terminal.',
        'if command -v osascript >/dev/null 2>&1; then',
        '  osascript -e "tell application \\"Terminal\\" to do script \\"node \\\\\\"$PANEL\\\\\\" --root \\\\\\"$HERE\\\\\\"\\""',
        'else',
        '  node "$PANEL" --root "$HERE"',
        'fi',
        '',
    ].join('\n');
}

function main() {
    const rootArg = process.argv.indexOf('--root');
    if (rootArg < 0 || !process.argv[rootArg + 1]) {
        console.error('用法：node make-launcher.mjs --root <团队根>');
        process.exit(1);
    }
    const teamRoot = resolve(process.argv[rootArg + 1]);
    const dotDir = join(teamRoot, '.tvs-boss');
    if (!existsSync(dotDir)) mkdirSync(dotDir, { recursive: true });

    const cmdPath = join(dotDir, 'panel.cmd');
    const shPath = join(dotDir, 'panel.command');
    writeFileSync(cmdPath, cmdTemplate(PANEL));
    writeFileSync(shPath, shTemplate(PANEL), { mode: 0o755 }); // mac/linux 需可执行位

    console.log('已生成启动器（panel.mjs=' + PANEL + '）：');
    console.log('  ' + cmdPath);
    console.log('  ' + shPath);
}

main();
