#!/usr/bin/env node
/**
 * tvs-boss 面板「一键启动器」生成器 —— 按团队生成，落到团队根的 .tvs-boss/ 里。
 *
 * 为什么要"生成"而不是把启动器塞进 skill 源码：
 *   - 启动器是「运行态产物」，每个用户的团队根各异，属于团队数据（.tvs-boss/）而非工具本体。
 *   - 启动器里唯一的机器相关值是 open-panel.mjs 的安装路径——它在【生成这一刻】由本脚本自身位置算出，
 *     绝不写回 skill 源码；团队根则由启动器运行时用 %~dp0 / $(dirname) 自定位，零硬编码盘符。
 *   - 生成的启动器是「薄壳」：只自定位团队根 + 调 open-panel.mjs，平台开窗逻辑全在 open-panel 一处。
 *
 * 用法：node make-launcher.mjs --root <团队根>
 *   把 panel.cmd（Windows）和 panel.command（mac/linux）都写进 <团队根>/.tvs-boss/。
 *   两个平台的都生成——同步过去的团队目录换台机器也开箱即用。
 *
 * /tvs-boss 启动协议在「建团 / 恢复团队」时调用本脚本，即可让每个用户初始化后就地有启动器。
 */
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// open-panel.mjs 绝对路径：由本生成器自身位置推出（同目录），生成器内零硬编码
const OPENER = join(dirname(fileURLToPath(import.meta.url)), 'open-panel.mjs');

/**
 * Windows 启动器（.cmd）：薄壳——只负责自定位团队根 + 调 open-panel.mjs，
 * 平台开窗/wt 检测等逻辑全收敛在 open-panel.mjs 一处（单一真源，改窗口行为不用动两份）。
 * @param {string} openerPath 生成时填入的 open-panel.mjs 绝对路径
 */
function cmdTemplate(openerPath) {
    // 注意：.cmd 正文保持纯 ASCII —— cmd.exe 在 chcp 生效前用 OEM 代码页(GBK)解析批处理字节，
    // 中文注释/echo 会被当成命令报错。中文交给被拉起的 node TUI 去显示。
    return [
        '@echo off',
        'rem tvs-boss panel launcher (generated by make-launcher.mjs; do NOT commit to skill source)',
        'rem Thin shim: self-locate team root via %~dp0, delegate window-opening to open-panel.mjs.',
        'rem open-panel.mjs path is filled at generation time from the skill install location.',
        'set "HERE=%~dp0"',
        'set "HERE=%HERE:~0,-1%"',
        `node "${openerPath}" --root "%HERE%"`,
        '',
    ].join('\r\n');
}

/**
 * macOS/Linux 启动器（.command）：薄壳——自定位团队根 + 调 open-panel.mjs（开窗逻辑在那一处）。
 * @param {string} openerPath 生成时填入的 open-panel.mjs 绝对路径
 */
function shTemplate(openerPath) {
    return [
        '#!/usr/bin/env bash',
        '# tvs-boss panel launcher (generated by make-launcher.mjs; do NOT commit to skill source)',
        '# Thin shim: self-locate team root, delegate window-opening to open-panel.mjs.',
        'HERE="$(cd "$(dirname "$0")" && pwd)"',
        `node "${openerPath}" --root "$HERE"`,
        '',
    ].join('\n');
}

function main() {
    const rootArg = process.argv.indexOf('--root');
    if (rootArg < 0 || !process.argv[rootArg + 1]) {
        console.error('用法：node make-launcher.mjs --root <团队根>');
        process.exit(1);
    }
    const teamRoot = resolve(process.argv[rootArg + 1]);
    const dotDir = join(teamRoot, '.tvs-boss');
    if (!existsSync(dotDir)) mkdirSync(dotDir, { recursive: true });

    const cmdPath = join(dotDir, 'panel.cmd');
    const shPath = join(dotDir, 'panel.command');
    writeFileSync(cmdPath, cmdTemplate(OPENER));
    writeFileSync(shPath, shTemplate(OPENER), { mode: 0o755 }); // mac/linux 需可执行位

    console.log('已生成启动器（open-panel.mjs=' + OPENER + '）：');
    console.log('  ' + cmdPath);
    console.log('  ' + shPath);
}

main();
